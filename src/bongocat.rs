//! Dot-matrix bitmap OLED renderer for the Toykit v2 dongle.
//!
//! Renders a 128x64 SSD1306 OLED with:
//!   * top row           : WPM text on the left, battery icon + percent on
//!                         the right
//!   * left column       : current layer number, then firmware version
//!   * bottom-right area : an 80x40 cat-plays-bongo sprite, adapted from
//!                         Shepardskin's CC0 Cat Sprites (OpenGameArt #21390).
//!                         Two bitmap frames (CAT_DOWN / CAT_UP) are toggled
//!                         on every fresh key press, simulating alternating
//!                         drum hits.
//!
//! Sprite licence:
//!     Adapted from CC0 1.0 Universal Sprites by Shepardskin (2014),
//!     downloaded from <https://opengameart.org/node/21390>.
//!     Modifications (Pose: sit between two bongos; orientation: facing
//!     right; rendering style: 1-bpp MSB-first) are released under the
//!     same CC0 terms.  The bitmap data is auto-generated by
//!     `gen_cc0_cat.py` (do not hand-edit the byte arrays below).
//!
//! Layout (128x64 SSD1306, top-left origin):
//!
//!     0                                                          127
//!   0 +-----------------------------------------------------------+
//!     |  WPM:NN                  [battery icon]                  |
//!  10 +-----------------------------------------------------------+
//!     |  Layer:N                                       75%        |
//!  22 +-----------------------------------------------------------+
//!     |  V3.33                  [ 80x40 CC0 cat + 2 bongos    ]  |
//!  63 +-----------------------------------------------------------+
//!
//! All comments and source identifiers use ASCII only to avoid encoding
//! traps; emojis / box-drawing characters are intentionally absent.
//!
//! Compatibility notes (vs. Toykit v2 / RMK / embedded-graphics 0.8.x):
//!   * `RenderContext::battery` is a tuple struct `BatteryStatusEvent(pub BatteryStatus)`
//!     where `BatteryStatus` is an enum with two variants:
//!     - `Unavailable`                              -> show "--%"
//!     - `Available { charge_state, level: Option<u8> }`
//!     When level is `Some(p)`, treat `p` as the percent; otherwise treat as unknown.
//!   * `ImageRaw::new` in 0.8.x takes only `(data, width)`; height is
//!     inferred from `data.len() / width`.

